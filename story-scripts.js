// 本文の追加・修正ができる（story.jsのバージョンを上げ直す必要はない）。
//
// ----------------------------------------------------------
// ■ 1冊分の書き方
// ----------------------------------------------------------
// STORY_BOOK_SCRIPTS は「章番号(1〜10) → コマンドの配列」というオブジェクト。
// 配列の先頭から順番に1つずつ再生される（現時点では分岐なしの一本道）。
//
//   const STORY_BOOK_SCRIPTS = {
//       1: [ ...本文1の配列... ],
//       2: [ ...本文2の配列... ],
//       ...
//   };
//
// まだ本文ができていない章はキーごと書かなくてよい（その場合「読む」を押すと
// 「準備中」表示になる。book-09, book-10 のように解放条件が未定の章も同様）。
//
// ----------------------------------------------------------
// ■ 使えるコマンド一覧
// ----------------------------------------------------------
//  { bg: '画像パス' }
//      背景（一枚絵）を切り替える。次にbgが指定されるまでそのまま表示され続ける。
//
//  { char: '画像パス' }  または  { char: null }
//      画面下寄りに人物の立ち絵を表示する。nullを指定すると立ち絵を消す。
//      省略した場合は直前の立ち絵の表示状態を維持する（毎回書かなくてよい）。
//
//  { bgm: '音声パス' }
//      BGMを切り替える。直前と同じ曲を指定した場合は鳴らし直さない（自然に流れ続ける）。
//      省略した場合はそれまでのBGM（この本を開く前に鳴っていた図書館BGM等）がそのまま続く。
//
//  { se: '音声パス' }
//      効果音を1回だけ再生する（他のコマンドと同じ行に併記もできる。例: { bg:'...', se:'...' }）。
//
//  { say: '話者名', text: '本文' }
//      セリフ。タイプライターで表示され、タップで文字送り／次のコマンドへ進む。
//      話者名は左上（メッセージウインドウの枠に重なる位置）に表示される。
//
//  { narration: '本文' }
//      ナレーション（地の文）。話者名を出さずにセリフと同じ見た目で表示する。
//      say同様、タップで次のコマンドへ進む。
//
//  { wait: ミリ秒 }
//      指定した時間だけ、タップを待たずに自動で間を置いてから次のコマンドへ進む。
//      （例: 効果音や背景切り替えの余韻を持たせたい時などに使う）
//
//  { end: true }
//      ここで本編終了とし、本の拡大画面（表紙）に戻す。
//      配列の最後まで再生し終えた場合も、書かなくても自動的に同じ扱いになる。
//
// bg/char/bgm/seは単独のコマンドとしても、say/narrationと同じ行に併記しても良い。
// 例: { bg:'story/book01/scene2.png', se:'story/book01/thunder.mp3', narration:'……' }
//
// ----------------------------------------------------------
// ■ 今後、分岐（選択肢）を追加したくなった場合
// ----------------------------------------------------------
// 現状は「今は不要、将来的に検討したい」とのことなので実装していないが、
// 配列の中に { choice: [...] } のようなコマンドを1つ足す形で拡張できるように
// エンジン側の構造は作ってある（say/narrationの選択肢まわりの仕組みを流用できる）。
// 実際に必要になったタイミングで改めて設計する。
// ============================================================

