// このファイルには「絵・音・文章の並び」だけを書く。story.js（再生エンジン側）は一切編集しない。
// エンジンとデータを分けているので、以後は基本的にこのファイルの書き換えだけで
// 本文の追加・修正ができる（story.jsのバージョンを上げ直す必要はない）。
//
// ----------------------------------------------------------
// ■ 全体の構成（絵本風・ページ送り方式）
// ----------------------------------------------------------
// STORY_BOOK_SCRIPTS は「章番号(1〜10) → ページの配列」というオブジェクト。
//
//   const STORY_BOOK_SCRIPTS = {
//       1: [ ...本文1のページ配列... ],
//       2: [ ...本文2のページ配列... ],
//       ...
//   };
//
// まだ本文ができていない章はキーごと書かなくてよい（その場合「読む」を押すと
// 「準備中」表示になる。book-09, book-10 のように解放条件が未定の章も同様）。
//
// 1冊 = ページの配列。ページが表示されると、画像・BGM等の準備が整った状態で1秒待ってから
// 最初の文章が表示される。ページが切り替わった瞬間、前のページの文章は必ず消える。
// 画面をタップすると、そのページの中の文章を1つずつ進め、ページの文章を全部表示し終えた状態で
// さらにタップすると次のページにめくれる（進む時・戻る時どちらもページめくりの効果音が鳴る）。
// 前のページに戻りたい時は、読書中に画面左端に常設される「◀」ボタンで戻れる（現在のページの
// 先頭に戻る形。それ以上戻れない先頭ページでは「◀」は自動的に隠れる）。
//
// ----------------------------------------------------------
// ■ 1ページの書き方
// ----------------------------------------------------------
//   {
//       bg: '背景画像パス',        // ページ全体の背景紙（省略時は前のページの背景を維持）
//       image: '正方形画像パス',   // 挿絵。横中央・縦中央よりやや上に1枚だけ表示（省略時は前のページの挿絵を維持）
//       overlay: true/false,      // 挿絵の上に黒い半透明オーバーレイを重ねるか（省略時はページ切替時に自動でfalseに戻る）
//       blackout: true/false,     // 画面全体をゆっくり黒一色にする演出（省略時はページ切替時に自動でfalseに戻る）
//       silhouette: {...} | null, // キャラクターシルエットの初期表示（省略時はページ切替時に自動で非表示に戻る）
//       bgm: '音声パス' | null,   // メインBGM。nullを指定すると停止。省略時は前のページのBGMを維持
//       ambient: '音声パス' | null, // 雨音などの環境音（BGMに重ねてループ再生）。nullで停止。省略時は前のページの状態を維持
//       se: '音声パス',            // ページが表示された瞬間に1回だけ鳴らす効果音（省略可）
//       beats: [ ...そのページで表示する文章／演出の配列... ],
//   }
//
// 挿絵とテキストエリアは縦に並べて表示するので、文章の長さに関わらず挿絵と重ならない。
//
// ----------------------------------------------------------
// ■ beats（そのページ内の文章／演出）の書き方
// ----------------------------------------------------------
// 1つのbeatには、次のキーを必要な分だけ組み合わせて書ける。
//
//  文章（どれか1つ。省略すると「文章を持たない制御用beat」になる。下記参照）
//   { text: '本文' }
//       挿絵下のテキストエリアに、タイプライターなし・効果音なしで即座に表示する「絵本風」の
//       文章。タップで次のbeatへ（切り替え式）。文章は「」で囲まず、地の文をそのまま書く
//       （表示にあたって鉤括弧を付ける／付けないの判断はしない。書いた通りに表示される）。
//       会話文をキャラクター名付きで見せたい場合は、地の文の中に「店主「おい」」のように
//       名前＋鉤括弧のセリフをそのまま書き込む（下記の館長会話のような、名前を別枠に出す
//       専用UIは本編の文章表示では使わない）。
//   { centerText: '本文' }
//       画面全体が暗転（blackout: true）している時に、画面中央へゆっくりフェードイン／
//       アウトしながら表示する特別な文章（エンディング等の演出用）。タップで次のbeatへ。
//
//  （参考）以下はエンジン側には残っているが、現状book-01では使用していない表示方法：
//   { say: '話者名', text: '本文' } / { narration: '本文' }
//       咖喱図書館の会話で使っているメッセージウインドウ（タイプライター表示＋メッセージ音、
//       話者名を別枠に表示）を流用する方式。本編の文章では現在使用しない方針だが、
//       将来的に必要になった場合のために、エンジン側の対応は残してある。
//
//  演出（文章と自由に組み合わせられる。すべて省略可）
//   image: '画像パス'             挿絵をこのbeatの時点で差し替える（以後、次に指定されるまで維持）
//   overlay: true/false           黒いオーバーレイの表示切替
//   blackout: true/false          画面全体の暗転の切替（CSSのtransitionでゆっくりフェードする）
//   silhouette: {...} | null      キャラクターシルエットの表示・更新／nullで非表示（下記参照）
//   bgm: '音声パス' | null        メインBGMの切替／nullで停止
//   ambient: '音声パス' | null    環境音の切替／nullで停止
//   se: '音声パス'                このbeatが処理された瞬間に1回だけ鳴らす効果音
//   delay: ミリ秒                 このbeatの中身（上記の演出／文章）を反映する前に、
//                                  何も表示しないまま指定時間だけ静かに待つ
//   closeDisabled: true/false     読書中の「×」「◀」ボタンの有効／無効（演出上、途中で
//                                  離脱させたくない場面で使う。デフォルトは有効=false）
//
//  文章（text/centerText/say/narration）を持たないbeatは「制御用beat」として扱われ、画像切替や
//  BGM停止といった演出だけを適用したら、タップを待たずに自動的に次のbeatへ進む
//  （wait: ミリ秒 を指定すると、その時間だけ待ってから自動で次へ進む。省略すると即座に次へ）。
//
// ■ silhouette（キャラクターシルエットを挿絵に重ねる）の書き方
// ----------------------------------------------------------
// 挿絵（image）を置き換えるのではなく、挿絵の上に重ねて表示する専用レイヤー。
// 一度指定すると、以降のbeatでsilhouetteキーを省略した場合は直前の表示をそのまま維持する。
//
//   silhouette: {
//       src: 'story/manimage01.svg', // シルエット画像
//       x: '50%', y: '55%',          // 挿絵の枠内での中心位置（%指定。省略時は中央 '50%'）
//       width: '70%',                // 大きさ（width基準。挿絵の枠の幅に対する%）
//       height: '25%',               // 大きさ（height基準にしたい場合はこちらを指定。widthより優先）
//       scale: 1,                    // width/heightに対してさらに拡大縮小したい時の倍率（省略可）
//       opacity: 0.8,                // 不透明度（0〜1。省略時は1＝完全に不透明）
//   }
//   silhouette: null    その時点でシルエットを非表示にする。
//
//   枠からはみ出す位置・大きさを指定すると、その部分は自動的に見切れる（枠でクリップされる）。
//
// ----------------------------------------------------------
// ■ 今後、分岐（選択肢）を追加したくなった場合
// ----------------------------------------------------------
