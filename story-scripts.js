//
// ----------------------------------------------------------
// ■ 全体の構成（絵本風・ページ送り方式）
// ----------------------------------------------------------
// STORY_BOOK_SCRIPTS は「章番号(1〜10) → ページの配列」というオブジェクト。
//
//   const STORY_BOOK_SCRIPTS = {
//       1: [ ...本文1のページ配列... ],
//       2: [ ...本文2のページ配列... ],
//       ...
//   };
//
// まだ本文ができていない章はキーごと書かなくてよい（その場合「読む」を押すと
// 「準備中」表示になる。book-09, book-10 のように解放条件が未定の章も同様）。
//
// 1冊 = ページの配列。画面をタップすると、そのページの中の文章を1つずつ進め、
// ページの文章を全部表示し終えた状態でさらにタップすると次のページにめくれる。
// 前のページに戻りたい時は、読書中に画面左端に常設される「◀」ボタンで戻れる（現在のページの
// 先頭に戻る形。それ以上戻れない先頭ページでは「◀」は自動的に隠れる）。
//
// ----------------------------------------------------------
// ■ 1ページの書き方
// ----------------------------------------------------------
//   {
//       bg: '背景画像パス',        // そのページの背景（省略時は前のページの背景を維持）
//       image: '正方形画像パス',   // 挿絵。横中央・縦中央よりやや上に1枚だけ表示（省略可）
//       bgm: '音声パス',           // 省略時は前のページのBGMを維持（同じ曲なら鳴らし直さない）
//       se: '音声パス',            // ページが表示された瞬間に1回だけ鳴らす効果音（省略可）
//       beats: [ ...そのページで表示する文章の配列... ],
//   }
//
// imageには、通常の挿絵だけでなく「正方形の枠に収まるキャラクターシルエット画像
// （例: story/manimage01.svg）」を指定してもよい。扱いはどちらも同じ（挿絵の代わりに
// シルエット画像を表示するイメージ）。
//
// ----------------------------------------------------------
// ■ beats（そのページ内で表示する文章）の書き方
// ----------------------------------------------------------
// 1ページの中でも2種類の見せ方を自由に混在できる。
//
//  { text: '本文' }
//      挿絵の下のテキストエリアに、タイプライターなし・効果音なしで即座に表示する
//      「絵本風」の文章。タップすると、表示中の文章が次のbeatに置き換わる（切り替え式）。
//
//  { say: '話者名', text: '本文' }
//      咖喱図書館の会話でも使っているメッセージウインドウ（タイプライター表示＋
//      メッセージ音）でセリフを表示する。会話劇のようなシーンで使う。
//
//  { narration: '本文' }
//      sayと同じくメッセージウインドウを使うが、話者名を表示しない地の文。
//
// 1ページの中でbeatsを textで始めてsay/narrationに切り替える、といった混在も可能。
// （例: 絵本風の説明文の後に、キャラクター同士の会話をメッセージウインドウで見せる、など）
//
// ----------------------------------------------------------
// ■ 今後、分岐（選択肢）を追加したくなった場合
// ----------------------------------------------------------
// 現状は「今は不要、将来的に検討したい」とのことなので実装していない。
// 必要になったタイミングで、ページまたはbeatの仕組みを拡張する形で改めて設計する。
// ============================================================

